<#
.SYNOPSIS
    Словарь значений тега genre: какое значение к какой категории
    относится. По нему Get-Track раскладывает плоский список тегов на
    Intensity / Emotion / Scene / Game / Type, а мета-флаги идут отдельно
    (см. $script:RollGenreMetaTags).

.DESCRIPTION
    Словарь утверждён Мастером в ноябре 2026 года. Принцип: описать все
    треки как можно меньшим числом тегов. Новый тег заводится, только когда
    без него трек не описать.

      - Intensity, по нарастанию: Idle, Tension, Battle, Climax. Составные
        значения тоже пишутся по нарастанию: Idle,Tension, а не наоборот.
      - Emotion, от тёмного к светлому: Anger, Fear, Sorrow, Reverence,
        Curiosity, Light. Ступеней нет, каждое семейство - один тег.
      - Scene, двойное имя Группа(Тег). Группы на панели идут так: Rest,
        Road, Urban, Mystic, Dungeon, Action, Other. Road и Other -
        одиночные теги без группы и пишутся без скобок. Scene обязателен
        у каждого трека, кроме Type Intro, Outro и Effect.
      - Game: Fantasy, Modern, SciFi.
      - Type: Effect, Vocals, Intro, Outro.

    Скобки хранятся в теге как есть: в формате "Категория:a,b Категория:c"
    значения разделяет запятая, категории - пробел, а в "Rest(Tavern)" нет
    ни того, ни другого.

    Порядок строк в таблице ниже - это порядок показа на странице
    Start-WinampPlaylist для Intensity, Emotion и Scene: страница читает
    файл как текст. Переставлять строки - значит переставлять кнопки.

    Значения, которых нет в таблице, не теряются: Get-Track кладёт их в
    Unmatched.
#>
$script:RollGenreTaxonomy = @{
    # Intensity: что происходит на сцене, по нарастанию.
    'Idle'    = 'Intensity'
    'Tension' = 'Intensity'
    'Battle'  = 'Intensity'
    'Climax'  = 'Intensity'

    # Emotion: что чувствует слушатель, от тёмного к светлому.
    'Anger'     = 'Emotion'
    'Fear'      = 'Emotion'
    'Sorrow'    = 'Emotion'
    'Reverence' = 'Emotion'
    'Curiosity' = 'Emotion'
    'Light'     = 'Emotion'

    # Scene: где всё происходит и что это за сцена. Группа(Тег).
    'Rest(Tavern)'          = 'Scene'
    'Rest(Peaceful)'        = 'Scene'
    'Road'                  = 'Scene'
    'Urban(Town)'           = 'Scene'
    'Urban(Court)'          = 'Scene'
    'Mystic(Ritual)'        = 'Scene'
    'Mystic(Haunt)'         = 'Scene'
    'Dungeon(Ruins)'        = 'Scene'
    'Dungeon(Underworld)'   = 'Scene'
    'Action(Investigation)' = 'Scene'
    'Action(Chase)'         = 'Scene'
    'Action(Stealth)'       = 'Scene'
    'Other'                 = 'Scene'

    # Game: эпоха звучания.
    'Fantasy' = 'Game'
    'Modern'  = 'Game'
    'SciFi'   = 'Game'

    # Type: роль самой записи.
    'Effect' = 'Type'
    'Vocals' = 'Type'
    'Intro'  = 'Type'
    'Outro'  = 'Type'
}

<#
.SYNOPSIS
    Мета-флаги вне категорий: состояние трека в конвейере, а не свойство
    его звучания. Каждый становится отдельным булевым полем объекта
    Roll.MusicTrack, а не значением категории.

.DESCRIPTION
    Все три говорят об одном - берём ли мы трек в игру и что с ним
    делать дальше:

      Unsorted - подвешенное состояние. Либо ещё не слушали, либо
                 слушали и не решили; к игре допускается, в подборке
                 помечается звёздочкой.
      Excluded - отложен насовсем: слушать не хочется даже на пробу,
                 но пусть лежит на потом.
      Delete   - послушали, не понравилось; при ближайшей уборке уедет
                 в Music\Deleted.
#>
$script:RollGenreMetaTags = @('Delete', 'Excluded', 'Unsorted')

<#
.SYNOPSIS
    Canonical category order used when serializing a Roll.MusicTrack's
    parsed Genre categories back into the self-describing
    "Category:value1,value2" tag string (see ConvertTo-GenreTagString).
    Meta and Unmatched are appended last, in that order, when non-empty.
#>
$script:RollGenreCategoryOrder = @('Intensity', 'Emotion', 'Scene', 'Game', 'Type')

